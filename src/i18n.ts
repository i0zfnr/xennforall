export type Language = 'en' | 'ms';
let language: Language = (() => {
  try {
    return localStorage.getItem('xenn-language') === 'ms' ? 'ms' : 'en';
  } catch {
    return 'en';
  }
})();

const listeners = new Set<() => void>();
export function getLanguage() {
  return language;
}
export function subscribeLanguage(fn: () => void) {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}
export function setLanguage(value: Language) {
  language = value;
  document.documentElement.lang = value === 'ms' ? 'ms' : 'en';
  try {
    localStorage.setItem('xenn-language', value);
  } catch {}
  listeners.forEach((fn) => fn());
}

