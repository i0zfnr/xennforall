export function t(value: string): string {
  if (language === 'en') return value;
  if (value in ms) return ms[value];
  const patterns: [RegExp, (m: RegExpMatchArray) => string][] = [
    [/^(\d+) files? selected$/, (m) => `${m[1]} fail dipilih`],
    [/^Remove (.+)$/, (m) => `Buang ${m[1]}`],
    [/^Move (.+) up$/, (m) => `Alihkan ${m[1]} ke atas`],
    [/^Move page (\d+) left$/, (m) => `Alihkan halaman ${m[1]} ke kiri`],
    [/^Move page (\d+) right$/, (m) => `Alihkan halaman ${m[1]} ke kanan`],
    [/^Rotate page (\d+)$/, (m) => `Putar halaman ${m[1]}`],
    [/^Remove page (\d+)$/, (m) => `Buang halaman ${m[1]}`],
    [/^Original page (\d+)$/, (m) => `Halaman asal ${m[1]}`],
    [/^PDF page (\d+) of (\d+)$/, (m) => `Halaman PDF ${m[1]} daripada ${m[2]}`],
    [/^Rendering page (\d+) of (\d+)…$/, (m) => `Sedang memaparkan halaman ${m[1]} daripada ${m[2]}…`],
    [/^Choose a page between (\d+) and (\d+)\.$/, (m) => `Pilih halaman antara ${m[1]} dan ${m[2]}.`],
    [/^(\d+) pages available\.$/, (m) => `${m[1]} halaman tersedia.`],
    [/^(\d+) of (\d+) pages kept\. Drag or use the controls on each page\.$/, (m) => `${m[1]} daripada ${m[2]} halaman dikekalkan. Seret atau gunakan butang pada setiap halaman.`],
    [/^Downloading AI model · (\d+)%$/, (m) => `Sedang memuat turun model AI · ${m[1]}%`],
    [/^Processing image · (\d+)%$/, (m) => `Sedang memproses imej · ${m[1]}%`],
    [/^(.+) preview$/, (m) => `Pratonton ${t(m[1])}`],
    [/^Compare original with (.+)$/, (m) => `Bandingkan imej asal dengan ${t(m[1])}`],
  ];
  for (const [pattern, format] of patterns) {
    const match = value.match(pattern);
    if (match) return format(match);
  }
  return value;
}
